import { createRoot } from 'react-dom/client';
import App from './App';
import { defaultPacks, initialSave, makeCard, packs, players } from './game';

const KEY = 'fco-ui-preview';
const ids = [...players].sort((a, b) => b.ovr - a.ovr).filter((_, i) => i % 7 === 0).slice(0, 60).map(p => p.id);
const save = { ...initialSave(), balance: 1_250_000_000, fc: 12_500, stp: 45, cards: ids.map((id, i) => ({ ...makeCard(id), level: 1 + (i % 9) })),
  unopened: Object.fromEntries([...defaultPacks, ...packs].slice(0, 12).map(p => [p.id, 3])), taxVouchers: { 30: 1, 10: 2 } };
const store: Record<string, string> = { [KEY]: JSON.stringify(save) };
const storage = { getItem: (k: string) => store[k] ?? null, setItem: (k: string, v: string) => { store[k] = v; } };
createRoot(document.getElementById('root')!).render(<App storage={storage} storageKey={KEY} accountName="tester"/>);

const view = new URLSearchParams(location.search).get('view') ?? '';
const click = (el: Element | null | undefined) => (el as HTMLElement | null)?.click();
setTimeout(() => {
  if (!view) return;
  if (view === 'history') click(document.querySelector('.app-dock-icons button[title="Lịch sử"]'));
  else if (view === 'settings') click(document.querySelector('.app-dock-icons button[title="Cài đặt"]'));
  else if (view === 'stp') click(document.querySelector('.wallet-stp'));
  else click([...document.querySelectorAll('.app-dock-items button')].find(b => b.textContent?.trim().startsWith(view)));
}, 1500);
