// node tests/market-smoke.mjs <path-to-taste-skill/scripts/lib/cdp.mjs>
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { initialSave, players, STORAGE_KEY } from '../src/game.ts';
const { Browser, sleep } = await import(pathToFileURL(process.argv[2]).href);
const browser = await Browser.launch();
mkdirSync('.taste-skill/market/qa', { recursive: true });
try {
  const page = await browser.newPage();
  const url = pathToFileURL(resolve('mothe.html')).href;
  const saved = () => page.eval(key => JSON.parse(localStorage.getItem(key)), STORAGE_KEY);
  const click = async selector => { await page.eval(s => { const el = document.querySelector(s); if (!el || el.disabled) throw new Error('Unavailable: ' + s); el.click(); }, selector); await sleep(150); };
  const select = async (selector, value) => { await page.eval(({ selector, value }) => { const el = document.querySelector(selector); el.value = value; el.dispatchEvent(new Event('change', { bubbles: true })); }, { selector, value }); await sleep(100); };
  const search = async value => { await page.eval(value => { const el = document.querySelector('.market-filters input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, value); el.dispatchEvent(new Event('input', { bubbles: true })); }, value); await sleep(100); };
  const marketNav = '.main-nav button:nth-child(5)';
  const fixture = { ...initialSave(), reduced: true, sound: false };
  await page.goto(url, { settleMs: 400 });
  await page.eval(({ key, save }) => localStorage.setItem(key, JSON.stringify(save)), { key: STORAGE_KEY, save: fixture });
  await page.goto(url, { settleMs: 400 });
  await click(marketNav);
  assert.match(await page.eval(() => document.querySelector('h1').textContent), /Thị trường/);
  assert.equal(await page.eval(() => document.querySelectorAll('.market-row').length), 8);
  assert.equal(await page.eval(() => Number(document.querySelector('.market-tabs button span').textContent)), players.length);
  const firstPageName = await page.eval(() => document.querySelector('.market-player b').textContent);
  await click('[aria-label="Trang thị trường sau"]');
  assert.notEqual(await page.eval(() => document.querySelector('.market-player b').textContent), firstPageName);
  await select('[aria-label="Sắp xếp thị trường"]', 'ovr');
  for (const width of [1440, 768, 390]) {
    await page.setViewport({ width, height: 900, mobile: width === 390 });
    await page.screenshot({ path: `.taste-skill/market/qa/buy-${width}.jpg`, fullPage: true });
    assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false, `No overflow at ${width}`);
  }
  await click('.market-filter-toggle');
  assert.equal(await page.eval(() => document.querySelector('.market-filter-toggle').getAttribute('aria-expanded')), 'true');
  await search('khongco123');
  assert.ok(await page.eval(() => !!document.querySelector('.market-empty')));
  await click('.market-empty button');
  await search('nguyen hoang duc');
  assert.equal(await page.eval(() => document.querySelectorAll('.market-row').length), 1);
  await select('[aria-label="Mùa thẻ trên thị trường"]', 'origin');
  await select('[aria-label="Vị trí trên thị trường"]', 'CM');
  await select('[aria-label="Cấp thẻ trên thị trường"]', '3');
  await click('.market-row-action');
  const beforeCancel = await saved();
  assert.match(await page.eval(() => document.querySelector('.trade-player p').textContent), /\+3/);
  await page.screenshot({ path: '.taste-skill/market/qa/confirm-390.jpg' });
  await click('.trade-actions .secondary-button');
  await sleep(350);
  assert.deepEqual(await saved(), beforeCancel);

  await click('.market-row-action');
  await page.eval(() => { window.realMarketSetItem = Storage.prototype.setItem; Storage.prototype.setItem = () => { throw new Error('Storage blocked for test'); }; });
  await click('.confirm-trade');
  assert.deepEqual(await saved(), beforeCancel, 'Failed persistence keeps inventory and balance unchanged');
  assert.ok(await page.eval(() => !!document.querySelector('.trade-error')));
  await page.eval(() => { Storage.prototype.setItem = window.realMarketSetItem; });
  await page.eval(() => { const button = document.querySelector('.confirm-trade'); button.click(); button.click(); });
  await sleep(400);
  const bought = await saved();
  assert.equal(bought.cards.length, fixture.cards.length + 1, 'Double confirmation buys once');
  assert.equal(bought.cards[0].playerId, 30);
  assert.equal(bought.cards[0].level, 3);
  assert.equal(bought.balance, fixture.balance, 'Unlimited mode preserves balance');
  assert.equal(bought.history.length, 1);
  await page.goto(url, { settleMs: 400 });
  assert.deepEqual(await saved(), bought, 'Market history survives reload without resetting save');
  await click(marketNav);
  await click('.market-tabs button:nth-child(2)');
  await select('[aria-label="Cấp thẻ trên thị trường"]', '3');
  await click('.market-row-action');
  await page.eval(() => { const button = document.querySelector('.confirm-trade'); button.click(); button.click(); });
  await sleep(400);
  const sold = await saved();
  assert.equal(sold.cards.length, fixture.cards.length);
  assert.ok(!sold.cards.some(card => card.uid === bought.cards[0].uid));
  assert.equal(sold.history.length, 2);
  assert.equal(sold.balance, fixture.balance);
  await click('.market-count button');
  await page.screenshot({ path: '.taste-skill/market/qa/sell-390.jpg', fullPage: true });

  // A sold or consumed card in another tab must not be paid out again.
  await search('nguyen hoang duc');
  await click('.market-row-action');
  const staleId = fixture.cards.find(card => card.playerId === 30).uid;
  await page.eval(({ key, cardId }) => {
    const state = JSON.parse(localStorage.getItem(key));
    state.cards = state.cards.filter(card => card.uid !== cardId);
    localStorage.setItem(key, JSON.stringify(state));
    dispatchEvent(new StorageEvent('storage', { key, newValue: JSON.stringify(state) }));
  }, { key: STORAGE_KEY, cardId: staleId });
  await sleep(100);
  const beforeStale = await saved();
  await click('.confirm-trade');
  assert.ok(await page.eval(() => !!document.querySelector('.trade-error')));
  assert.deepEqual(await saved(), beforeStale);
  await click('[aria-label="Đóng xác nhận giao dịch"]');
  await sleep(350);
  await click('.market-heading .text-action');
  assert.equal(await page.eval(() => document.querySelector('[aria-label="Lọc loại lịch sử"]').value), 'market');
  assert.equal(await page.eval(() => document.querySelectorAll('.history-item').length), 2);
  // Selling a selected upgrade card must also clear its slot.
  await click('.main-nav button:nth-child(2)');
  const target = (await saved()).cards[0];
  const material = (await saved()).cards.find(card => card.uid !== target.uid);
  const materialName = players.find(player => player.id === material.playerId).name;
  await click('.material-slot:not(.filled)');
  await page.eval(name => [...document.querySelectorAll('.picker-row')].find(row => row.querySelector('.picker-name>b').textContent === name).click(), materialName);
  await click('.picker-modal .modal-bottom-button');
  assert.equal(await page.eval(() => document.querySelectorAll('.material-slot.filled').length), 1);
  const sellNamed = async name => {
    await click(marketNav);
    await click('.market-tabs button:nth-child(2)');
    await search(name);
    await click('.market-row-action');
    await click('.confirm-trade');
    await sleep(350);
  };
  await sellNamed(materialName);
  await click('.main-nav button:nth-child(2)');
  assert.equal(await page.eval(() => document.querySelectorAll('.material-slot.filled').length), 0);
  await sellNamed(players.find(player => player.id === target.playerId).name);
  await click('.main-nav button:nth-child(2)');
  assert.ok(!(await saved()).cards.some(card => card.uid === target.uid));
  assert.ok(await page.eval(() => !!document.querySelector('.target-button .player-card')));
  assert.deepEqual(page.consoleErrors, []);
  console.log('PASS: market buy/sell, +3 card, cancel, double-click protection, storage failure, stale sale, reload, history, search/filter/pagination; 1440/768/390px; no JavaScript errors.');
} finally { await browser.close(); }
