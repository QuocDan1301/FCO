import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const { Browser, sleep } = await import(pathToFileURL(process.argv[2]).href);
const browser = await Browser.launch();
const url = pathToFileURL(path.resolve('mothe.html')).href;
const out = '.taste-skill/icon-tm-qa'; mkdirSync(out, { recursive: true });
try {
  const page = await browser.newPage();
  const requests = [], errors = [];
  await page.send('Network.enable');
  browser.on(page.sessionId, 'Network.requestWillBeSent', e => { if (/^https?:/.test(e.request.url)) requests.push(e.request.url); });
  browser.on(page.sessionId, 'Runtime.consoleAPICalled', e => { if (e.type === 'error') errors.push(e.args.map(a => a.value || a.description).join(' ')); });
  await page.send('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: 0, uploadThroughput: 0 });
  await page.goto(url, { settleMs: 1000 });
  await page.eval(() => document.fonts.ready);
  const click = async (s, batch = false) => { if (s.startsWith('.ready-open')) { const start = Date.now(); while (!(await page.eval(s => !!document.querySelector(s + ':not(:disabled)'), s))) { if (Date.now() - start > 8000) throw new Error('Cảnh chưa sẵn sàng'); await sleep(40); } } await page.eval(s => { const b = document.querySelector(s); if (!b || b.disabled) throw new Error(`Control unavailable: ${s}`); b.click(); }, s); await sleep(90); if (s === '.hero-button') { const start = Date.now(); while (!(await page.eval(() => !!document.querySelector('.ready-open-one:not(:disabled)')))) { if (Date.now() - start > 8000) throw new Error('Cảnh chưa sẵn sàng'); await sleep(40); } await page.eval(batch => document.querySelector(batch ? '.ready-open-batch' : '.ready-open-one').click(), batch); await sleep(90); } };
  const wait = async (expression, timeout = 6000) => { const start = Date.now(); while (!(await page.eval(expression))) { if (Date.now() - start > timeout) throw new Error('Timeout: ' + expression); await sleep(60); } };
  const stage = n => wait(`!!document.querySelector('.opening-phase-${n}')`);
  const saved = () => page.eval(() => JSON.parse(localStorage.getItem('arena-huyen-thoai-v1')));
  const shot = async name => { await sleep(230); return page.screenshot({ path: `${out}/${name}.jpg` }); };
  const forceMessi = () => page.eval(() => { let i = 0; crypto.getRandomValues = a => { a[0] = i++ % 2 === 0 ? 4294967295 : 644245094; return a; }; });
  await click('.sound-button');
  await forceMessi();
  await page.eval(() => { const b = document.querySelector('.hero-button'); b.click(); b.click(); b.click(); });
  await click('.ready-open');
  const committed = await saved(); assert.equal(committed.opened, 1); assert.equal(committed.cards.length, 13);
  await stage(2); await shot('desktop-emblem');
  const initialZ = await page.eval(() => document.querySelector('.three-stadium')?.dataset.cameraZ);
  await stage(3); await wait("!!document.querySelector('.information-3')"); assert.match(await page.eval(() => document.querySelector('.opening-information').textContent), /Argentina/); await shot('desktop-nation');
  await stage(4); await wait("!!document.querySelector('.information-4')"); assert.match(await page.eval(() => document.querySelector('.opening-information').textContent), /RW/); await shot('desktop-position');
  await stage(5); await wait("!!document.querySelector('.information-5')"); assert.match(await page.eval(() => document.querySelector('.opening-information').textContent), /Đội tuyển đại diệnArgentina/); await shot('desktop-team');
  await stage(6); await shot('desktop-silence');
  await stage(7); await shot('desktop-door');
  await stage(8); await shot('desktop-stage');
  assert.equal(await page.eval(() => document.querySelector('.three-stadium')?.dataset.cardCenter), '0.00');
  await stage(9); await sleep(950); await shot('desktop-player');
  const finalZ = await page.eval(() => document.querySelector('.three-stadium')?.dataset.cameraZ);
  if (initialZ && finalZ) assert.ok(Number(finalZ) < Number(initialZ) - 15, 'Camera thực sự di chuyển trong không gian');
  assert.equal((await saved()).cards.length, committed.cards.length);
  assert.match(await page.eval(() => document.querySelector('.opening-player-meta').textContent), /Argentina/);
  await click('.opening-stats-button');
  assert.equal(await page.eval(() => document.querySelectorAll('.opening-stats>div:last-child>span').length), 6);
  await click('.save-reward');
  assert.equal((await saved()).cards.length, 13, 'Lưu vào kho không cộng lại phần thưởng');
  await click('.main-nav button:nth-child(1)');
  await click('.opening-mode-toggle');
  await forceMessi();
  const fastStart = Date.now(); await click('.hero-button', true);
  await stage(9); assert.ok(Date.now() - fastStart < 7000, 'Chế độ nhanh khoảng 4,5 giây sau khi cảnh sẵn sàng');
  await wait("document.querySelectorAll('.opening-batch-grid>div').length === 10", 5000);
  assert.equal((await saved()).cards.length, 23); assert.equal((await saved()).opened, 11); await shot('desktop-ten');
  await click('.opening-skip');
  await page.setViewport({ width: 768, height: 1024 });
  await forceMessi(); await click('.hero-button');
  await stage(5); await shot('tablet-team');
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  await click('.opening-skip'); await click('.opening-skip');
  await page.setViewport({ width: 390, height: 844, mobile: true });
  await click('.opening-mode-toggle');
  await forceMessi(); await click('.hero-button');
  await stage(3); await shot('mobile-three-nation');
  if (await page.eval(() => !!document.querySelector('.three-stadium'))) assert.equal(await page.eval(() => document.querySelector('.three-stadium').dataset.reflection), '128');
  await click('.opening-quality');
  assert.ok(await page.eval(() => !!document.querySelector('[data-renderer="light"]')));
  await shot('mobile-light-nation');
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  await click('.opening-skip'); await stage(9); await sleep(1000); await shot('mobile-result');
  const beforeReload = await saved();
  await page.goto(url, { settleMs: 500 });
  assert.equal((await saved()).cards.length, beforeReload.cards.length);
  assert.equal((await saved()).opened, beforeReload.opened);
  await click('[aria-label="Mở cài đặt"]');
  await click('.setting-row:nth-of-type(2) input');
  await click('[aria-label="Đóng cài đặt"]');
  await click('.hero-button'); await sleep(200); await stage(9);
  assert.equal(await page.eval(() => document.querySelectorAll('.three-stadium, .light-cinema-canvas').length), 0);
  assert.deepEqual(requests, []); assert.deepEqual(page.consoleErrors, []); assert.deepEqual(errors, []);
  console.log('PASS: file ngoại tuyến; camera/LED/cửa/sân khấu; quốc tịch → vị trí → đội tuyển; khoảng lặng; kết quả lưu trước; chống lặp; Lưu không nhân đôi; nhanh; tự tổng kết 10; fallback 2D; điện thoại; tải lại; giảm chuyển động; không lỗi JavaScript/WebGL.');
} finally { await browser.close(); }
