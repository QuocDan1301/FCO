import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const { Browser, sleep } = await import(pathToFileURL(process.argv[2]).href);
const browser = await Browser.launch();
try {
  const page = await browser.newPage();
  const url = pathToFileURL(path.resolve('mothe.html')).href;
  const click = async selector => { if (selector.startsWith('.ready-open')) { const started = Date.now(); while (!(await page.eval(s => !!document.querySelector(s + ':not(:disabled)'), selector))) { if (Date.now() - started > 8000) throw new Error('Cảnh chưa sẵn sàng'); await sleep(40); } } await page.eval(s => { const b = document.querySelector(s); if (!b || b.disabled) throw new Error('Nút không khả dụng: ' + s); b.click(); }, selector); await sleep(120); };
  const saved = () => page.eval(() => { const s = JSON.parse(localStorage.getItem('arena-huyen-thoai-v1')); return s ? { opened: s.opened, count: s.cards.length, stock: s.unopened?.eternal ?? 15 } : { opened: 0, count: 12, stock: 15 }; });
  const textOf = selector => page.eval(s => document.querySelector(s).textContent, selector);
  await page.goto(url, { settleMs: 500 });
  await click('.hero-button');
  assert.equal(await page.eval(() => document.querySelectorAll('.ready-actions button').length), 2);
  assert.match(await textOf('.ready-open-one'), /Mở 1 thẻ/);
  assert.match(await textOf('.ready-open-batch'), /Mở 10 thẻ/);
  assert.deepEqual(await saved(), { opened: 0, count: 12, stock: 15 });
  await page.screenshot({ path: '.taste-skill/icon-tm-qa/ready-desktop.jpg' });
  await click('.ready-close'); await click('.sound-button');
  await page.eval(() => { const key = 'arena-huyen-thoai-v1'; const s = JSON.parse(localStorage.getItem(key)); s.reduced = true; s.sound = false; localStorage.setItem(key, JSON.stringify(s)); });
  await page.goto(url, { settleMs: 300 });
  await click('.hero-button');
  await page.eval(() => { const b = document.querySelector('.ready-open-batch'); b.click(); b.click(); b.click(); });
  await sleep(450);
  assert.deepEqual(await saved(), { opened: 10, count: 22, stock: 5 });
  assert.equal(await page.eval(() => document.querySelectorAll('.opening-batch-grid>div').length), 10);
  await click('.open-next');
  assert.match(await textOf('.ready-open-batch'), /Mở 5 thẻ/);
  assert.deepEqual(await saved(), { opened: 10, count: 22, stock: 5 });
  await page.setViewport({ width: 390, height: 844, mobile: true });
  await page.screenshot({ path: '.taste-skill/icon-tm-qa/ready-mobile.jpg' });
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  await click('.ready-close'); await page.goto(url, { settleMs: 300 });
  await click('.hero-button');
  assert.match(await textOf('.ready-open-batch'), /Mở 5 thẻ/);
  await click('.ready-open-batch'); await sleep(450);
  assert.deepEqual(await saved(), { opened: 15, count: 27, stock: 0 });
  assert.equal(await page.eval(() => document.querySelectorAll('.opening-batch-grid>div').length), 5);
  await click('.open-next');
  assert.equal(await page.eval(() => [...document.querySelectorAll('.ready-actions button')].every(b => b.disabled)), true);
  await click('.ready-close'); await click('.receive-test-packs');
  assert.deepEqual(await saved(), { opened: 15, count: 27, stock: 10 });
  await click('.hero-button'); await click('.ready-open-one'); await sleep(250);
  assert.deepEqual(await saved(), { opened: 16, count: 28, stock: 9 });
  await click('.opening-skip');
  await page.eval(() => { const key = 'arena-huyen-thoai-v1'; const s = JSON.parse(localStorage.getItem(key)); s.unopened.eternal = 1; localStorage.setItem(key, JSON.stringify(s)); });
  await page.goto(url, { settleMs: 300 }); await click('.hero-button');
  assert.equal(await page.eval(() => document.querySelector('.ready-open-one').disabled), false);
  assert.equal(await page.eval(() => document.querySelector('.ready-open-batch').disabled), true);
  await click('.ready-open-one'); await sleep(250);
  assert.deepEqual(await saved(), { opened: 17, count: 29, stock: 0 });
  assert.deepEqual(page.consoleErrors, []);
  console.log('PASS: đúng hai nút; 15 → mở 10 → còn 5; nhãn Mở 5; nhận đủ 5; hết gói khóa nút; một gói mở được; nhận thêm gói thử; hủy và tải lại không nhận trùng; chống lặp; mobile không tràn.');
} finally { await browser.close(); }
