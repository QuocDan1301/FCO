import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const { Browser, sleep } = await import(pathToFileURL(process.argv[2]).href);
const browser = await Browser.launch();
const url = pathToFileURL(path.resolve('mothe.html')).href;
const out = '.taste-skill/tunnel-qa';
mkdirSync(out, { recursive: true });
try {
  const page = await browser.newPage();
  const requests = [];
  await page.send('Network.enable');
  browser.on(page.sessionId, 'Network.requestWillBeSent', event => { if (/^https?:/.test(event.request.url)) requests.push(event.request.url); });
  await page.send('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: 0, uploadThroughput: 0 });
  await page.goto(url, { settleMs: 1000 });
  await page.eval(() => document.fonts.ready);
  const click = async selector => { await page.eval(s => { const button = document.querySelector(s); if (!button || button.disabled) throw new Error(`Control unavailable: ${s}`); button.click(); }, selector); await sleep(100); };
  const saved = () => page.eval(() => localStorage.getItem('arena-huyen-thoai-v1'));
  const phase = n => page.eval(n => !!document.querySelector(`.pack-cinema.phase-${n}`), n);
  const shot = name => page.screenshot({ path: `${out}/${name}.jpg` });
  const forceMessi = () => page.eval(() => { let index = 0; crypto.getRandomValues = array => { array[0] = index++ % 2 === 0 ? 4294967295 : 644245094; return array; }; });
  await forceMessi();
  await click('.hero-button');
  const committed = await saved();
  await sleep(700);
  await shot('desktop-entry');
  assert.equal(await page.eval(() => document.querySelectorAll('.tunnel-rib').length), 12);
  assert.equal(await page.eval(() => getComputedStyle(document.querySelector('.tunnel-world')).transformStyle), 'preserve-3d');
  await sleep(900);
  assert.ok(await phase(1));
  await shot('desktop-nation');
  await sleep(1200);
  assert.ok(await phase(2));
  await shot('desktop-club');
  await sleep(1200);
  assert.ok(await phase(3));
  assert.ok(await page.eval(() => !!document.querySelector('.gate-opening')));
  await shot('desktop-gate-opening');
  await sleep(1200);
  assert.ok(await phase(4));
  await shot('desktop-ovr-walkout');
  await sleep(1700);
  assert.ok(await phase(5));
  assert.equal(await saved(), committed, 'Hoạt cảnh không tính lại hoặc thay đổi kết quả');
  await shot('desktop-result');
  await click('.cinema-top button');
  await page.setViewport({ width: 768, height: 1024 });
  await forceMessi();
  await click('.hero-button');
  await sleep(1900);
  await shot('tablet-nation');
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  await click('.cinema-top button');
  await click('.cinema-top button');
  await page.setViewport({ width: 390, height: 844, mobile: true });
  await forceMessi();
  await click('.hero-button');
  await sleep(1900);
  await shot('mobile-nation');
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  await sleep(3600);
  await shot('mobile-walkout');
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  await click('.cinema-top button');
  assert.ok(await phase(5));
  await sleep(1400);
  assert.ok(await phase(5), 'Bỏ qua không quay lại đường hầm');
  await click('.cinema-top button');
  await click('[aria-label="Chọn Gói Khởi nguyên"]');
  await page.eval(() => { crypto.getRandomValues = array => { array[0] = 0; return array; }; });
  await click('.hero-button');
  assert.ok(await page.eval(() => !!document.querySelector('.tunnel-standard')));
  await sleep(3500);
  assert.ok(await phase(5), 'Thẻ thường có hoạt cảnh ngắn hơn');
  await click('.cinema-top button');
  await click('[aria-label="Mở cài đặt"]');
  await click('.setting-row:nth-of-type(2) input');
  await click('[aria-label="Đóng cài đặt"]');
  await click('.hero-button');
  await sleep(150);
  assert.ok(await phase(5));
  assert.equal(await page.eval(() => document.querySelectorAll('.tunnel-scene').length), 0, 'Giảm chuyển động không dựng đường hầm 3D');
  assert.deepEqual(requests, [], 'Bản HTML không gọi mạng');
  assert.deepEqual(page.consoleErrors, []);
  console.log('PASS: đường hầm 3D, cửa mở, 5 bước hé lộ, kết quả tính trước, thẻ thường/hiếm, bỏ qua, giảm chuyển động, màn hình 390px và HTML ngoại tuyến.');
} finally { await browser.close(); }
