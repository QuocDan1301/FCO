import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const { Browser, sleep } = await import(pathToFileURL(process.argv[2]).href);
const browser = await Browser.launch();
try {
  const page = await browser.newPage();
  const mobile = process.argv.includes('--mobile');
  if (mobile) await page.setViewport({ width: 390, height: 844, mobile: true });
  const wait = async (fn, timeout = 8000) => { const started = Date.now(); while (!(await page.eval(fn))) { if (Date.now() - started > timeout) throw new Error('Chờ cảnh quá lâu'); await sleep(40); } };
  await page.goto(pathToFileURL(path.resolve('mothe.html')).href, { settleMs: 400 });
  await page.eval(() => document.querySelector('.hero-button').click());
  await wait(() => !!document.querySelector('.ready-open-one:not(:disabled)'));
  assert.ok(await page.eval(() => !!document.querySelector('.persistent-pack-scene canvas')), 'Cảnh đã được chuẩn bị trước khi nhấn mở');
  await page.eval(() => {
    window.warmedCanvas = document.querySelector('.persistent-pack-scene canvas');
    window.openClicked = performance.now(); window.flipFrames = []; let last = performance.now();
    const sample = now => { window.flipFrames.push(now - last); last = now; if (!document.querySelector('.icon-opening')) requestAnimationFrame(sample); };
    requestAnimationFrame(sample);
    const b = document.querySelector('.ready-open-one'); b.click(); b.click(); b.click();
  });
  await sleep(1650);
  assert.equal(await page.eval(() => !!document.querySelector('.is-flipping')), false, 'Chờ 2 giây trước khi lật');
  assert.equal(await page.eval(() => document.querySelector('.persistent-pack-scene')?.dataset.playing), 'false');
  assert.equal(await page.eval(() => document.querySelector('.ready-open-one').disabled), true, 'Khóa mở lặp trong lúc chờ');
  await wait(() => !!document.querySelector('.pack-ready-modal.is-flipping .ready-flip'));
  const flipDelay = await page.eval(() => performance.now() - window.openClicked);
  assert.ok(flipDelay >= 1950 && flipDelay < 2600, `Bắt đầu lật sau 2 giây: ${flipDelay}ms`);
  assert.equal(await page.eval(() => JSON.parse(localStorage.getItem('arena-huyen-thoai-v1')).opened), 1);
  assert.ok(await page.eval(() => parseFloat(getComputedStyle(document.querySelector('.ready-flip')).animationDuration) >= 1.8), 'Lật chậm đủ để đọc mặt sau');
  await sleep(1450);
  assert.ok(await page.eval(() => !!document.querySelector('.is-flipping')), 'Giữ mặt trắng trong nhịp dừng trước đường hầm');
  const movingZ = await page.eval(() => Number(document.querySelector('.three-stadium')?.dataset.cameraZ ?? 12));
  assert.ok(await page.eval(() => document.querySelector('.persistent-pack-scene')?.dataset.playing === 'false'), 'Camera chờ hết nhịp dừng mặt trắng');
  assert.ok(Math.abs(movingZ - 13) < .01, 'Camera giữ nguyên vị trí trong nhịp dừng');
  assert.equal(await page.eval(() => getComputedStyle(document.querySelector('.flip-back')).backgroundColor), 'rgb(255, 255, 255)');
  assert.equal(await page.eval(() => getComputedStyle(document.querySelector('.flip-back>strong')).opacity), '0');
  await wait(() => !!document.querySelector('.icon-opening[data-scene-ready="true"]'));
  assert.equal(await page.eval(() => !!document.querySelector('.opening-entry-veil')), false, 'Không chèn màn đen ở chỗ nối');
  assert.ok(await page.eval(z => Number(document.querySelector('.three-stadium')?.dataset.cameraZ ?? 0) <= z, movingZ), 'Camera không trở về điểm xuất phát');
  assert.equal(await page.eval(() => window.warmedCanvas === document.querySelector('.persistent-pack-scene canvas')), true, 'Giữ nguyên canvas khi vào đường hầm');
  const frames = await page.eval(() => window.flipFrames.filter(v => v > 0).sort((a, b) => a - b));
  console.log(JSON.stringify({ flipFrames: frames.length, p95: frames[Math.floor(frames.length * .95)], longest: Math.max(...frames) }));
  assert.ok(frames.length >= 20, 'Hiệu ứng lật có đủ khung hình');
  assert.ok(Math.max(...frames) < 200, 'Không có lần khởi tạo GPU làm đứng hiệu ứng lật');
  assert.equal(await page.eval(() => !!document.querySelector('.opening-quality')), false, 'Ẩn nút tùy chỉnh trong hoạt cảnh');
  await wait(() => !!document.querySelector('.opening-skip'));
  await page.eval(() => document.querySelector('.opening-skip').click());
  await wait(() => !!document.querySelector('.opening-phase-9'));
  assert.deepEqual(page.consoleErrors, []);
  console.log('PASS: lật sang mặt trắng sáng; dừng một nhịp rồi mới chạy camera; không màn đen/khởi động lại ở chỗ nối; chế độ nhẹ giữ đồng hồ; chống nhấn lặp; bỏ qua giữ đúng thưởng.');
} finally { await browser.close(); }
