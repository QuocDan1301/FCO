// Kiểm thử trình duyệt độc lập, dùng CDP helper có sẵn của kỹ năng thiết kế.
// node tests/browser-smoke.mjs <đường-dẫn-tới-scripts/lib/cdp.mjs> [http://127.0.0.1:5173]
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const { Browser, sleep } = await import(pathToFileURL(process.argv[2]).href);
const baseUrl = process.argv[3] || 'http://127.0.0.1:5173';
const browser = await Browser.launch();
mkdirSync('.taste-skill/game-qa', { recursive: true });
try {
  const page = await browser.newPage();
  const state = () => page.eval(() => JSON.parse(localStorage.getItem('arena-huyen-thoai-v1')));
  const click = async (selector) => { await page.eval(s => { const b = document.querySelector(s); if (!b) throw new Error(`Missing ${s}`); if (b.disabled) throw new Error(`Disabled ${s}`); b.click(); }, selector); await sleep(150); };
  const text = () => page.eval(() => document.body.innerText);
  const shot = name => page.screenshot({ path: `.taste-skill/game-qa/${name}.jpg`, fullPage: true });
  await page.goto(baseUrl);
  assert.match(await text(), /Chạm tới/);
  await click('.odds-link');
  assert.match(await text(), /55%/);
  await click('[aria-label="Đóng bảng tỷ lệ"]');
  await page.eval(() => { const button = document.querySelector('.hero-button'); button.click(); button.click(); button.click(); });
  await sleep(150);
  assert.equal((await state()).opened, 1, 'Chặn nhấn lặp');
  assert.equal((await state()).cards.length, 13);
  assert.equal((await state()).balance, 13500000);
  await click('.cinema-top .secondary-button');
  await sleep(1200);
  assert.equal(await page.eval(() => !!document.querySelector('.is-finished')), true, 'Bỏ qua không quay lại hoạt cảnh');
  await shot('pack-single');
  await click('.cinema-top .secondary-button');
  await page.goto(baseUrl + '/mothe.html');
  assert.equal((await state()).cards.length, 13, 'Giữ kho sau tải lại');
  await click('[aria-label="Chọn Gói Khởi nguyên"]');
  await click('.batch-bar .secondary-button');
  await click('.cinema-top .secondary-button');
  assert.equal((await state()).opened, 11);
  assert.equal((await state()).cards.length, 23);
  assert.equal((await state()).balance, 12500000);
  assert.equal(await page.eval(() => document.querySelectorAll('.batch-results>.best-result').length), 1);
  assert.equal(await page.eval(() => document.querySelectorAll('.batch-results>div').length), 10);
  await shot('pack-ten');
  await click('.cinema-top .secondary-button');
  await click('.main-nav button:nth-child(2)');
  const chooseMaterials = async () => {
    await click('.material-slot:not(.filled)');
    for (let i = 1; i <= 5; i++) await click(`.picker-row:nth-child(${i})`);
    await click('.picker-modal .modal-bottom-button');
  };
  await chooseMaterials();
  await shot('upgrade-ready');
  const beforeSuccess = await state();
  await page.eval(() => { crypto.getRandomValues = array => { array[0] = 0; return array; }; });
  await click('.upgrade-controls>.primary-button');
  await click('.cinema-top .secondary-button');
  assert.match(await text(), /Nâng cấp thành công!/);
  const afterSuccess = await state();
  assert.equal(afterSuccess.cards.length, beforeSuccess.cards.length - 5);
  assert.equal(afterSuccess.balance, beforeSuccess.balance - 100000);
  assert.equal(afterSuccess.upgrades, 1);
  await shot('upgrade-success');
  await click('.upgrade-result-copy .primary-button');
  await chooseMaterials();
  await page.eval(() => { crypto.getRandomValues = array => { array[0] = 4294967295; return array; }; });
  const beforeFailure = await state();
  await click('.upgrade-controls>.primary-button');
  await click('.cinema-top .secondary-button');
  assert.match(await text(), /Nâng cấp thất bại/);
  const afterFailure = await state();
  assert.equal(afterFailure.cards.length, beforeFailure.cards.length - 5);
  assert.equal(afterFailure.balance, beforeFailure.balance - 200000);
  assert.equal(afterFailure.upgrades, 2);
  assert.equal(afterFailure.history[0].success, false);
  await shot('upgrade-failure');
  await click('.upgrade-result-copy .primary-button');
  await click('.main-nav button:nth-child(3)');
  await page.eval(() => { const input = document.querySelector('.search-field input'); const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; setter.call(input, 'khongcoabcxyz'); input.dispatchEvent(new Event('input', { bubbles: true })); });
  await sleep(150);
  assert.match(await text(), /Chưa tìm thấy cầu thủ/);
  await click('.empty-state .secondary-button');
  assert.ok(await page.eval(() => document.querySelectorAll('.collection-card').length > 0));
  await click('.daily-button');
  assert.equal((await state()).balance, afterFailure.balance + 1000000);
  assert.equal(await page.eval(() => document.querySelector('.daily-button').disabled), true);
  await click('.main-nav button:nth-child(4)');
  assert.equal(await page.eval(() => document.querySelectorAll('.history-item').length), 5);
  await shot('history');
  await click('[aria-label="Mở cài đặt"]');
  await click('.setting-row:nth-of-type(2) input');
  await click('[aria-label="Đóng cài đặt"]');
  assert.equal((await state()).reduced, true);
  await page.setViewport({ width: 390, height: 844, mobile: true });
  await click('.main-nav button:nth-child(2)');
  await shot('mobile-upgrade');
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  await click('.main-nav button:nth-child(3)');
  await shot('mobile-collection');
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  await click('.main-nav button:nth-child(1)');
  await click('.hero-button');
  await sleep(200);
  assert.equal(await page.eval(() => !!document.querySelector('.is-finished')), true, 'Giảm chuyển động công bố ngay');
  await click('.cinema-top .secondary-button');
  assert.deepEqual(page.consoleErrors, []);
  console.log('PASS: mở gói, chống lặp, bỏ qua, mở 10, lưu sau tải lại, nâng cấp thành công/thất bại, lọc kho, điểm danh, lịch sử, giảm chuyển động và bố cục 390px. Không lỗi JavaScript.');
} finally { await browser.close(); }
