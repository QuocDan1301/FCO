import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import { mkdirSync } from 'node:fs';
const { Browser, sleep } = await import(pathToFileURL(process.argv[2]).href);
const browser = await Browser.launch();
const url = pathToFileURL(path.resolve('mothe.html')).href;
mkdirSync('.taste-skill/standalone-qa', { recursive: true });
try {
  const page = await browser.newPage();
  const requests = [];
  await page.send('Network.enable');
  browser.on(page.sessionId, 'Network.requestWillBeSent', event => { if (/^https?:/.test(event.request.url)) requests.push(event.request.url); });
  await page.send('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: 0, uploadThroughput: 0 });
  await page.goto(url, { settleMs: 600 });
  assert.match(await page.eval(() => document.querySelector('h1').textContent), /Chạm tới/);
  assert.ok(await page.eval(() => [...document.images].every(i => i.complete && i.naturalWidth > 0)));
  await page.eval(() => document.fonts.ready);
  assert.ok(await page.eval(() => document.fonts.check('16px "Be Vietnam Pro"')), JSON.stringify(await page.eval(() => [...document.fonts].map(f => ({ family: f.family, status: f.status, weight: f.weight })))));
  const click = async selector => { await page.eval(s => { const b = document.querySelector(s); if (!b || b.disabled) throw new Error('Control unavailable: ' + s); b.click(); }, selector); await sleep(130); };
  const state = () => page.eval(() => JSON.parse(localStorage.getItem('arena-huyen-thoai-v1')));
  await click('.hero-button');
  assert.equal((await state()).cards.length, 13);
  await click('.cinema-top button');
  assert.ok(await page.eval(() => !!document.querySelector('.is-finished')));
  await click('.cinema-top button');
  await click('.main-nav button:nth-child(2)');
  await click('.material-slot');
  await click('.picker-row');
  await click('.picker-modal .modal-bottom-button');
  await click('.upgrade-controls>.primary-button');
  await click('.cinema-top button');
  assert.equal((await state()).cards.length, 12);
  assert.equal((await state()).upgrades, 1);
  await click('.cinema-top button');
  await page.goto(url, { settleMs: 400 });
  assert.equal((await state()).cards.length, 12);
  assert.equal((await state()).opened, 1);
  await page.screenshot({ path: '.taste-skill/standalone-qa/desktop.jpg' });
  await page.setViewport({ width: 390, height: 844, mobile: true });
  await page.screenshot({ path: '.taste-skill/standalone-qa/mobile.jpg' });
  assert.equal(await page.eval(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(requests, [], 'Không có yêu cầu HTTP: HTML hoạt động hoàn toàn ngoại tuyến');
  assert.deepEqual(page.consoleErrors, []);
  console.log('PASS: mothe.html mở trực tiếp bằng file:// khi ngắt mạng; font/ảnh đã nhúng; mở gói, nâng cấp, lưu sau tải lại, bố cục điện thoại hoạt động; không gọi HTTP và không lỗi JavaScript.');
} finally { await browser.close(); }
